"""Extract one-bit firmware artwork from the maintainer's pixel-exact reference."""
from pathlib import Path
import hashlib
import json
from PIL import Image

ROOT = Path(__file__).resolve().parent
REPO = ROOT.parents[2]
OUT = REPO / 'src/vario/ui/display/pages/primary/charging_dialog_art.h'
INK = (33, 37, 42)
FG = (199, 204, 193)


def packed(mask):
    result = []
    for y in range(mask.height):
        for x in range(0, mask.width, 8):
            result.append(sum(1 << bit for bit in range(8)
                              if x + bit < mask.width and mask.getpixel((x + bit, y))))
    return result


def bits(image):
    image = image.convert('RGB')
    mask = Image.new('1', image.size)
    mask.putdata([pixel != INK for pixel in image.get_flattened_data()])
    return mask


def main():
    reference = Image.open(ROOT / 'reference/dialog-spec.png').convert('RGB')
    frames = json.loads((ROOT / 'reference/frames.json').read_text())
    lines = ['// Generated by docs/ui-reviews/charging-dialog-revamp/extract_assets.py.',
             '// Artwork copied from the supplied pixel reference; XBM bit ordering.',
             '#pragma once', '#include <Arduino.h>', '', 'namespace charging_art {',
             'struct Glyph { const uint8_t* pixels; uint8_t x, y, width, height; };']

    def array(name, mask):
        data = packed(mask)
        lines.append(f'const uint8_t {name}[] PROGMEM = {{')
        for start in range(0, len(data), 16):
            lines.append('  ' + ', '.join(f'0x{value:02x}' for value in data[start:start+16]) + ',')
        lines.append('};')

    def glyph(name, box, source, raise_by=0):
        mask = bits(source.crop(box))
        array(name + '_bits', mask)
        lines.append(f'const Glyph {name} = {{{name}_bits, {box[0]}, {box[1]-raise_by}, {mask.width}, {mask.height}}};')

    source = Image.open(ROOT / 'reference/connecting-00.png').convert('RGB')
    # Leaf symbols reuse leaf_8x14 characters 140 and 142. Only unique artwork
    # is stored in firmware; animation frames below are simulator fixtures only.
    glyph('wordmark', (47, 4, 66, 17), source)
    glyph('device', (14, 20, 29, 50), source, raise_by=1)
    glyph('cloud', (57, 21, 92, 41), source, raise_by=1)
    complete = Image.open(ROOT / 'reference/complete-00.png').convert('RGB')
    glyph('checkmark', (36, 27, 54, 41), complete, raise_by=1)
    # The new failure glyph shares the check's height and center. Keep it
    # reproducible here so refreshing the reference artwork preserves it.
    failure = Image.new('1', (14, 14))
    for y in range(14):
        for x in range(14):
            failure.putpixel((x, y), abs(x - y) <= 1 or abs(x + y - 13) <= 1)
    lines.append('// Two-pixel diagonal strokes, shared by the final frame and compact result.')
    array('failure_bits', failure)
    lines.append('const Glyph failure = {failure_bits, 38, 26, 14, 14};')
    from PIL import ImageChops
    for i in range(1, 4):
        previous = bits(Image.open(ROOT / f'reference/wifi-{i-1:02}.png'))
        current = bits(Image.open(ROOT / f'reference/wifi-{i:02}.png'))
        delta = ImageChops.difference(previous, current)
        box = delta.getbbox()
        array(f'wifi_{i}_bits', delta.crop(box))
        lines.append(f'const Glyph wifi_{i} = {{wifi_{i}_bits, {box[0]}, {box[1]-1}, {box[2]-box[0]}, {box[3]-box[1]}}};')
    usb = reference.crop((14, 152, 110, 174))
    glyph('usb_icon', (3, 2, 42, 20), usb)
    fixture = bytearray()
    for group in ('scanning', 'wifi', 'connecting', 'uploading', 'complete'):
        for entry in frames:
            if entry['group'] != group:
                continue
            original = Image.open(ROOT / 'reference' / entry['file']).convert('RGB')
            assert original.tobytes() == reference.crop(entry['source_box']).tobytes()
            mask = bits(original)
            if group == 'scanning':
                # Maintainer correction: source frame 2 has a 3px bar and later
                # frames drift by 1px. Retain the original first two positions.
                for y in range(26, 44):
                    for x in range(17, 25):
                        mask.putpixel((x, y), 0)
                bar_y = 28 + 2 * entry['frame']
                for y in range(bar_y, bar_y + 2):
                    for x in range(17, 25):
                        mask.putpixel((x, y), 1)
            # The count is drawn dynamically. Leave the rounded corners untouched.
            if group in ('uploading', 'complete'):
                for y in range(41, 50):
                    for x in range(54, 94):
                        mask.putpixel((x, y), 0)
            # Raise only the interaction artwork by one row. Branding and the
            # rounded panel corners remain at their original coordinates.
            body = mask.crop((2, 18, 94, 50))
            for y in range(17, 50):
                for x in range(2, 94):
                    mask.putpixel((x, y), 0)
            mask.paste(body, (2, 17))
            fixture.extend(packed(mask))
    (ROOT / 'reference/expected-dialogs.bin').write_bytes(fixture)
    lines.append('}  // namespace charging_art\n')
    OUT.write_text('\n'.join(lines), encoding='utf-8')
    print('Extracted 9 shared firmware glyphs; 27 full frames are simulator-only fixtures.')
    print('Reference SHA256:', hashlib.sha256((ROOT / 'reference/dialog-spec.png').read_bytes()).hexdigest())


if __name__ == '__main__':
    main()
